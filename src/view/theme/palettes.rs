//! The 30 hand-tuned colour palettes and the [`ThemePalette`] shape they fill.
//!
//! This is data only. The active-index `static`, the modal navigation and the
//! per-role colour accessors (`bg()`, `track_color(color_slot)`, …) that
//! every renderer actually calls live in the parent module. See `030-ui-design.md` for the
//! contrast rules a new preset must follow.

use egui::Color32;

use crate::core::config::TRACK_COLOR_COUNT;

/// One colour theme: a name plus a colour for every UI role. `THEMES` holds 30.
#[derive(Clone, Copy)]
pub(super) struct ThemePalette {
    /// Display name in the settings modal's theme list.
    pub(super) name: &'static str,
    /// Window background.
    pub(super) bg: Color32,
    /// Header / status / modal panel background.
    pub(super) bg_panel: Color32,
    /// Timeline strip background.
    pub(super) bg_timeline: Color32,
    /// Separator lines.
    pub(super) separator: Color32,
    /// Major grid lines (bar boundaries).
    pub(super) grid_major: Color32,
    /// Primary text.
    pub(super) fg: Color32,
    /// Dimmed / secondary text.
    pub(super) fg_dim: Color32,
    /// Accent (highlights, selection).
    pub(super) accent: Color32,
    /// The playhead line.
    pub(super) playhead: Color32,
    /// The loop-region band.
    pub(super) region: Color32,
    /// White piano key.
    pub(super) piano_key_white: Color32,
    /// Black piano key.
    pub(super) piano_key_black: Color32,
    /// Per-track accent colours, indexed by a track's colour slot
    /// (`Track::color_slot`, `theme::track_color`). The first eight were
    /// hand-tuned; the last eight were generated to sit apart from them at
    /// the same lightness and chroma.
    pub(super) tracks: [Color32; TRACK_COLOR_COUNT],
    /// Fill for a lit **S** (solo) / **M** (mute) track-header button. Distinct
    /// hues — solo amber, mute red, DAW-conventional — so the two stay
    /// tellable apart when both are on.
    pub(super) track_solo: Color32,
    /// Fill for a lit **M** (mute) button — see [`track_solo`](Self::track_solo).
    pub(super) track_mute: Color32,
}

/// `0xRRGGBB` → [`Color32`].
const fn hex(hex: u32) -> Color32 {
    let r = ((hex >> 16) & 0xFF) as u8;
    let g = ((hex >> 8) & 0xFF) as u8;
    let b = (hex & 0xFF) as u8;
    Color32::from_rgb(r, g, b)
}

